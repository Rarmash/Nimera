static u32 *graphics_target_pixels;
static u64 graphics_target_width, graphics_target_height, graphics_target_stride;

static u32 *graphics_pixels(void) { return graphics_target_pixels != (u32 *)0 ? graphics_target_pixels : display_framebuffer(); }
static u64 graphics_width(void) { return graphics_target_pixels != (u32 *)0 ? graphics_target_width : display_width(); }
static u64 graphics_height(void) { return graphics_target_pixels != (u32 *)0 ? graphics_target_height : display_height(); }
static u64 graphics_stride(void) { return graphics_target_pixels != (u32 *)0 ? graphics_target_stride : display_pitch() / 4ULL; }

static u32 graphics_cyrillic_ascii(u32 codepoint)
{
	static const u32 upper[] = {'A','B','V','G','D','E','Z','Z','I','J','K','L','M','N','O','P','R','S','T','U','F','H','C','C','S','S','Y','E','U','A','B','V','G','D'};
	if (codepoint >= 0x0410U && codepoint <= 0x0431U) return upper[codepoint - 0x0410U];
	if (codepoint >= 0x0430U && codepoint <= 0x0451U) return graphics_cyrillic_ascii(codepoint - 0x20U);
	return 0U;
}

static const u16 *graphics_glyph(u32 codepoint)
{
	u32 mapped = graphics_cyrillic_ascii(codepoint);
	if (mapped != 0U) codepoint = mapped;
	if (codepoint >= 'A' && codepoint <= 'Z') return uppercase[codepoint - 'A'];
	if (codepoint >= 'a' && codepoint <= 'z') return lowercase[codepoint - 'a'];
	if (codepoint >= '0' && codepoint <= '9') return digits[codepoint - '0'];
	if (codepoint == '!') return glyph_exclamation;
	if (codepoint == '?') return glyph_question;
	if (codepoint == ':') return glyph_colon;
	if (codepoint == ';') return glyph_semicolon;
	if (codepoint == '.') return glyph_dot;
	if (codepoint == ',') return glyph_comma;
	if (codepoint == '/') return glyph_slash;
	if (codepoint == '\\') return glyph_backslash;
	if (codepoint == '[') return glyph_left_bracket;
	if (codepoint == ']') return glyph_right_bracket;
	if (codepoint == '{') return glyph_left_brace;
	if (codepoint == '}') return glyph_right_brace;
	if (codepoint == '(') return glyph_left_paren;
	if (codepoint == ')') return glyph_right_paren;
	if (codepoint == '<') return glyph_less;
	if (codepoint == '>') return glyph_greater;
	if (codepoint == '+') return glyph_plus;
	if (codepoint == '-') return glyph_minus;
	if (codepoint == '=') return glyph_equals;
	if (codepoint == '_') return glyph_underscore;
	if (codepoint == ' ') return (const u16 *)0;
	return glyph_replacement;
}

void graphics_put_pixel(u64 x, u64 y, u32 color)
{
	if (!display_available() || graphics_pixels() == (u32 *)0 || x >= graphics_width() || y >= graphics_height()) return;
	graphics_pixels()[y * graphics_stride() + x] = color;
}

void graphics_fill_rect(u64 x, u64 y, u64 w, u64 h, u32 color)
{
	if (!display_available() || graphics_pixels() == (u32 *)0 || x >= graphics_width() || y >= graphics_height()) return;
	if (w > graphics_width() - x) w = graphics_width() - x;
	if (h > graphics_height() - y) h = graphics_height() - y;
	for (u64 row = 0; row < h; ++row) for (u64 column = 0; column < w; ++column) graphics_put_pixel(x + column, y + row, color);
}

void graphics_clear(u32 color) { graphics_fill_rect(0, 0, graphics_width(), graphics_height(), color); }
void graphics_set_target(u32 *pixels, u64 width, u64 height, u64 stride) { graphics_target_pixels = pixels; graphics_target_width = width; graphics_target_height = height; graphics_target_stride = stride; }
void graphics_reset_target(void) { graphics_target_pixels = (u32 *)0; graphics_target_width = 0; graphics_target_height = 0; graphics_target_stride = 0; }
unsigned int graphics_glyph_width(void) { return 10U; }
unsigned int graphics_glyph_height(void) { return 18U; }
unsigned int graphics_cell_width(void) { return 10U; }
unsigned int graphics_cell_height(void) { return 18U; }

void graphics_draw_codepoint(u64 x, u64 y, u32 codepoint, u32 foreground, u32 background)
{
	const u16 *glyph = graphics_glyph(codepoint);
	render_stats_glyph_draw();
	graphics_fill_rect(x, y, graphics_cell_width(), graphics_cell_height(), background);
	if (glyph == (const u16 *)0) return;
	for (u64 row = 0; row < 9ULL; ++row) for (u64 column = 0; column < 10ULL; ++column)
		if ((glyph[row] >> (9ULL - column)) & 1U) graphics_fill_rect(x + column, y + row * 2ULL, 1ULL, 2ULL, foreground);
}

void graphics_draw_char(u64 x, u64 y, char character, u32 foreground, u32 background)
{ graphics_draw_codepoint(x, y, (u32)(unsigned char)character, foreground, background); }

void graphics_draw_text(u64 x, u64 y, const char *text, u32 color)
{
	while (*text != '\0') { graphics_draw_char(x, y, *text++, color, 0U); x += graphics_cell_width(); }
}

