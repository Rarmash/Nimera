static u32 cyrillic_to_latin(u32 cp)
{
	static const char map[] = "ABVGDEEZIIKLMNOPRSTUFHCCHSHYEYUABVGDE";
	if (cp >= 0x0430U && cp <= 0x044fU) return cyrillic_to_latin(cp - 0x20U);
	if (cp >= 0x0410U && cp <= 0x042fU) return (u32)map[cp - 0x0410U];
	if (cp == 0x0401U || cp == 0x0451U) return (u32)'E';
	return 0U;
}

const unsigned char *nimera_gui_font_rows(u32 cp)
{
	u32 mapped = cyrillic_to_latin(cp);
	if (mapped != 0U) cp = mapped;
	if (cp >= 'A' && cp <= 'Z') return letters[cp - 'A'];
	if (cp >= 'a' && cp <= 'z') return letters[26U + cp - 'a'];
	if (cp >= '0' && cp <= '9') return digits[cp - '0'];
	if (cp == ' ') return (const unsigned char *)0;
	if (cp >= '!' && cp <= '/') return punctuation[cp - '!'];
	if (cp >= ':' && cp <= '@') return punctuation[cp - ':' + 5U];
	return punctuation[3];
}
